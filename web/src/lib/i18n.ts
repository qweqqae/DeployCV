export type TranslationKey = keyof typeof translations.en;

export function t(locale: Locale, key: TranslationKey): string {
  return translations[locale][key];
}

export function detectLocale(languageCode?: string): Locale {
  return languageCode?.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

const STATUS_KEYS: Record<string, TranslationKey> = {
  online: 'statusOnline',
  coding: 'statusCoding',
  designing: 'statusDesigning',
  learning: 'statusLearning',
  custom: 'statusCustom',
};

export function getStatusLabel(locale: Locale, value: string): string {
  const key = STATUS_KEYS[value];
  return key ? t(locale, key) : value;
}

export function getSizeLabel(locale: Locale, size: 'sm' | 'md' | 'lg'): string {
  const map = { sm: 'sizeSmall', md: 'sizeMiddle', lg: 'sizeLarge' } as const;
  return t(locale, map[size]);
}

export function getGithubPaddingLabel(locale: Locale, size: 'none' | 'sm' | 'md' | 'lg' | 'xl'): string {
  if (size === 'xl') return t(locale, 'paddingXL');
  if (size === 'none') return t(locale, 'paddingNone');
  return getSizeLabel(locale, size);
}
